function makeDisplayNames(locale) {
  try {
    return new Intl.DisplayNames([locale], { type: "region" });
  } catch (error) {
    return null;
  }
}

function resolveCountryName(code, localizedNames, fallbackNames) {
  return localizedNames?.of(code) || fallbackNames?.of(code) || code;
}

export function getCountryNameOptions(locale = "en", currentValue = "") {
  const localizedNames = makeDisplayNames(locale);
  const fallbackNames =
    locale === "en" ? localizedNames : makeDisplayNames("en");

  const options = COUNTRY_CODES.map((code) =>
    resolveCountryName(code, localizedNames, fallbackNames)
  )
    .filter(Boolean)
    .filter((name) => !COUNTRY_CODES.includes(name))
    .sort((left, right) => left.localeCompare(right, locale));

  const current = String(currentValue || "").trim();
  if (current && !options.includes(current)) {
    options.unshift(current);
  }

  return Array.from(new Set(options));
}
